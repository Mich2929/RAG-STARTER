// Helper to generate smooth realistic chart curves
function generateChartPoints(basePrice: number, changePercent: number, count: number, volatility = 0.008): ChartPoint[] {
  const points: ChartPoint[] = [];
  const startPrice = basePrice / (1 + changePercent / 100);
  let currentPrice = startPrice;

  for (let i = 0; i < count; i++) {
    const progress = i / (count - 1);
    // Drift toward basePrice with random walk
    const target = startPrice + (basePrice - startPrice) * progress;
    const noise = (Math.sin(i * 0.45) * 0.4 + Math.cos(i * 0.9) * 0.3 + (Math.random() - 0.48)) * (basePrice * volatility);
    currentPrice = target + noise;
    
    // Create OHLC simulation
    const open = currentPrice - (Math.random() - 0.5) * (basePrice * volatility * 0.5);
    const close = currentPrice;
    const high = Math.max(open, close) + Math.random() * (basePrice * volatility * 0.4);
    const low = Math.min(open, close) - Math.random() * (basePrice * volatility * 0.4);

    const hours = 9 + Math.floor((i / count) * 7);
    const minutes = Math.floor(((i / count) * 420) % 60);
    const timeStr = `${hours.toString().padStart(2, '0')}:${minutes.toString().padStart(2, '0')}`;

    points.push({
      time: timeStr,
      price: Number(close.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume: Math.floor(150000 + Math.random() * 450000),
    });
  }

  // Ensure last point matches exactly
  if (points.length > 0) {
    points[points.length - 1].price = basePrice;
    points[points.length - 1].close = basePrice;
  }

  return points;
}

